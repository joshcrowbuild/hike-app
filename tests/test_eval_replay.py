"""The source-or-silence replay gate (Epic 009, golden-trip + cassette half).

Two halves, both load-bearing:
  * the gate HOLDS on the committed golden scenarios (the same run CI executes);
  * the gate BITES — a simulated engine regression (guardrail threshold gutted,
    source stamp stripped, a fabricated kind injected) must turn the report red.
    A regression gate that can't fail is a vacuous pass, exactly what the repo's
    falsifiability discipline (CI owner-isolation tests) exists to prevent.
"""

from __future__ import annotations

import dataclasses
import json
import re

import pytest

import orchestration.curator as curator
from evals.replay import (
    SCENARIOS_DIR,
    check_verdict_consistency,
    evaluate_scenario,
    list_scenario_dirs,
    load_scenario,
    run_scenario,
)

_EXPECTED_SCENARIOS = {
    "nominal-old-rag",
    "guardrail-trip-aqi",
    "hazard-warning-flashflood",
    "adapter-outage",
    "sparse-cold",
    "regional-alert-verdict-consistency",
    # GLM red-team fixes (2026-07): both joined the blocking gate when their fixes
    # landed — losing either would silently reopen a confirmed finding.
    "closure-alert-no-warning",
    "stale-degraded-untestable",
}


def _by_name(name: str):
    return load_scenario(SCENARIOS_DIR / name)


def test_golden_scenario_set_is_present() -> None:
    # The gate must never quietly shrink: losing a scenario is losing coverage.
    names = {p.name for p in list_scenario_dirs()}
    assert _EXPECTED_SCENARIOS <= names, f"missing scenarios: {_EXPECTED_SCENARIOS - names}"


@pytest.mark.parametrize("name", sorted(_EXPECTED_SCENARIOS))
def test_scenario_invariants_hold(name: str) -> None:
    # The same pass CI's eval-replay job runs — every criterion at rate 1.0.
    result = evaluate_scenario(_by_name(name), n=1)
    assert result.passed, f"{name} failed: {result.failures}"


def test_nominal_surfaces_the_golden_five_with_real_facts() -> None:
    batch = run_scenario(_by_name("nominal-old-rag"))
    ids = {t.candidate.canonical_id for t in batch.trails}
    assert "osm:old-rag-mountain-loop" in ids  # Old Rag is trip #1 (AC-3.4)
    assert len(batch.trails) == 5
    old_rag = next(
        t for t in batch.trails if t.candidate.canonical_id == "osm:old-rag-mountain-loop"
    )
    # CDP-01 wiring: the SAME_AS distinct-origin count reaches the plan (3 = NPS+OSM+USFS).
    assert old_rag.corpus_corroboration == 3
    assert set(old_rag.corpus_sources) == {"NPS", "OSM", "USFS"}


def test_guardrail_trip_sets_every_labeled_trail_aside() -> None:
    batch = run_scenario(_by_name("guardrail-trip-aqi"))
    assert not batch.trails  # hazardous AQI blocks every candidate
    aside = {t.canonical_id for t in batch.set_aside}
    expected = set(_by_name("guardrail-trip-aqi").expected["hard"]["must_be_blocked"])
    assert aside == expected
    # Every set-aside carries a sourced cause — disclosed, never silently dropped.
    assert all(r.source for t in batch.set_aside for r in t.reasons)


# ── falsifiability: a real engine regression must red the gate ────────────────


def test_gutted_guardrail_threshold_is_caught(monkeypatch) -> None:
    # Simulate the regression the gate exists for: the hazardous-AQI block silently
    # stops firing (threshold pushed above the recorded 250). The hand-labeled
    # must-be-blocked set (AC-3.2 — a cassette label, not a guardrail re-run) is
    # what catches it, which is exactly why the label must never be generated by
    # the code under test.
    monkeypatch.setattr(curator, "AQI_BLOCK", 10_000)
    result = evaluate_scenario(_by_name("guardrail-trip-aqi"), n=1)
    assert not result.passed
    assert "must_be_blocked_held" in result.failures


def test_stripped_source_stamp_is_caught(monkeypatch) -> None:
    # Simulate a source-or-silence regression: the weather fact loses its source
    # stamp. The core invariant criterion must go red.
    import orchestration.adapters.nws as nws

    monkeypatch.setattr(nws, "SOURCE", "")
    result = evaluate_scenario(_by_name("nominal-old-rag"), n=1)
    assert not result.passed
    assert "source_or_silence" in result.failures


def test_fabricated_kind_is_caught() -> None:
    # Simulate fabrication-on-absence: a kind the scenario's bundle cannot verify
    # (air, in sparse-cold) suddenly produces a fact. no_fabricated_kinds must red.
    sparse = _by_name("sparse-cold")
    nominal = _by_name("nominal-old-rag")
    tampered = dataclasses.replace(
        sparse, conditions={**sparse.conditions, "airnow": nominal.conditions["airnow"]}
    )
    result = evaluate_scenario(tampered, n=1)
    assert not result.passed
    assert "no_fabricated_kinds" in result.failures


def test_partial_alert_coverage_is_caught() -> None:
    # F1 (ux-review-conditions-2026-07, "one sky, one verdict"): a region-wide
    # alert reaching only SOME cards must red verdict_consistency — the card
    # missing it would derive "Good to go" while the feed banner (and its own
    # Detail, had the payload carried it) said "Caution". Tampering strips the
    # warning off one planned trail post-run, simulating exactly that partial
    # coverage.
    scenario = _by_name("regional-alert-verdict-consistency")
    batch = run_scenario(scenario)
    assert batch.trails, "scenario must surface cards to tamper with"
    stripped = dataclasses.replace(
        batch.trails[0], verdict=dataclasses.replace(batch.trails[0].verdict, warnings=())
    )
    tampered = dataclasses.replace(batch, trails=[stripped, *batch.trails[1:]])
    violations = check_verdict_consistency(tampered, scenario.expected["hard"])
    assert violations, "stripping a region-wide warning off one card must red the check"
    assert any("Beach Hazards Statement" in v for v in violations)


def test_regional_alert_rides_every_surfaced_card() -> None:
    # The green half of the same invariant: in the untampered golden run the
    # alert is on EVERY card's own warning set, source-stamped — the wire-level
    # guarantee that lets card and Detail derive one identical verdict.
    batch = run_scenario(_by_name("regional-alert-verdict-consistency"))
    assert len(batch.trails) >= 3
    for trail in batch.trails:
        texts = [w.text for w in trail.verdict.warnings]
        assert any("Beach Hazards Statement" in t for t in texts), texts
        assert all(w.source for w in trail.verdict.warnings)


def test_missing_expected_card_is_caught() -> None:
    # An empty feed must never read as green when the bundle should yield cards —
    # the anti-vacuous-pass criterion.
    nominal = _by_name("nominal-old-rag")
    tampered = dataclasses.replace(
        nominal, corpus={**nominal.corpus, "trailhead_rows": [], "direct_rows": []}
    )
    result = evaluate_scenario(tampered, n=1)
    assert not result.passed
    assert "surfaced_expected" in result.failures


def test_typoed_expectation_key_is_rejected_not_vacuously_green() -> None:
    # Self-review MODERATE (2026-07-11): a misspelled expected.json key must abort
    # loudly, never default to an empty expectation that passes every criterion.
    nominal = _by_name("nominal-old-rag")
    hard = dict(nominal.expected["hard"])
    hard["must_blocked"] = hard.pop("must_be_blocked")  # the typo
    tampered = dataclasses.replace(nominal, expected={**nominal.expected, "hard": hard})
    with pytest.raises(ValueError, match="must_be_blocked"):
        evaluate_scenario(tampered, n=1)


def test_unknown_condition_kind_reds_fidelity_not_a_traceback() -> None:
    # Self-review MINOR: a bad kind name in expected facts is a red criterion with a
    # named violation, not an uncaught ValueError killing the scenario walk.
    nominal = _by_name("nominal-old-rag")
    hard = {**nominal.expected["hard"], "facts": {"wether": {"source_prefix": "NWS"}}}
    tampered = dataclasses.replace(nominal, expected={**nominal.expected, "hard": hard})
    result = evaluate_scenario(tampered, n=1)
    assert not result.passed
    assert any("wether" in v for v in result.failures.get("fact_fidelity", []))


# ── GLM red-team F1/F2 (2026-07): the fixed findings hold AND bite ────────────


def test_closure_alert_rides_every_surfaced_card_as_a_warning() -> None:
    # F1 (HIGH): a verified NPS Closure alert is a prominent, source-stamped
    # CardWarning on every surfaced card — the frontend's deriveVerdict reads
    # warnings kind-agnostically, so the headline is "Caution", never "Good to go"
    # beside an active closure.
    batch = run_scenario(_by_name("closure-alert-no-warning"))
    assert batch.trails, "the closure scenario must surface cards"
    for trail in batch.trails:
        hits = [w for w in trail.verdict.warnings if "Old Rag Area Closure" in w.text]
        assert hits, [w.text for w in trail.verdict.warnings]
        assert all(w.kind == "closures" and w.source for w in hits)
    # Never a block and never a set-aside: safety is presentation (rule #2).
    assert not batch.set_aside


